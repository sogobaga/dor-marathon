-- Migration 151：跑步鼓勵語（GPS 跑步頁每跨一整公里彈出一句）。
-- 兩池：phase='before'（完成目標 50% 前，累積式文案，含佔位符 {done}，前台代入如「3 km」）、
-- phase='after'（超過 50% 後，剩餘式文案，含 {remain}，前台代入如「7 km」或「38 分鐘」）。
-- 後台可增刪改（見 internal/runcheer）；佔位符字面文字直接存 DB，由前台字串取代，後端不解析。

CREATE TABLE IF NOT EXISTS run_cheer_messages (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  phase TEXT NOT NULL CHECK (phase IN ('before','after')),
  text TEXT NOT NULL,
  enabled BOOLEAN NOT NULL DEFAULT TRUE,
  sort_order INT NOT NULL DEFAULT 0,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_run_cheer_phase ON run_cheer_messages(phase, enabled, sort_order);

